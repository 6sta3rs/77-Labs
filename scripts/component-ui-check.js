// Run on /inputy in an isolated browser profile:
// await (await import('/scripts/component-ui-check.js')).checkComponentGallery()
export async function checkComponentGallery() {
  const checks = []
  const assert = (name, condition) => { checks.push({ name, passed: !!condition }); if (!condition) throw new Error(name) }
  const wait = (ms = 40) => new Promise(resolve => setTimeout(resolve, ms))
  const button = (text, root = document) => [...root.querySelectorAll('button')].find(node => node.textContent.trim() === text)
  const visible = node => !!node && getComputedStyle(node).visibility !== 'hidden' && getComputedStyle(node).display !== 'none' && getComputedStyle(node).opacity !== '0'
  const fill = (input, value) => { input.value = value; input.dispatchEvent(new Event('input', { bubbles: true })) }
  const storageKeys = ['voicestudio.appearance.v2','voicestudio.themes.v1','voicestudio.projects.v2']
  const original = storageKeys.map(key => localStorage.getItem(key))
  try {
    button('Resetuj podgląd').click(); await wait()
    document.activeElement?.blur?.()
    for (const range of document.querySelectorAll('.vs-slider input')) range.dispatchEvent(new PointerEvent('pointerleave', { pointerType:'mouse' }))
    await wait()
    assert('Dymek suwaka ukryty w spoczynku', ![...document.querySelectorAll('.vs-slider-value')].some(visible))
    const slider = document.querySelector('#control-5 .vs-slider'), range = slider.querySelector('input')
    range.dispatchEvent(new PointerEvent('pointerenter', { pointerType:'mouse' })); await wait()
    assert('Dymek suwaka widoczny po hover', visible(document.querySelector('.vs-slider-value')))
    assert('Dymek pokazuje bieżącą wartość', document.querySelector('.vs-slider-value').textContent === '44%')
    window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true})); await wait()
    assert('Escape zamyka dymek', !document.querySelector('.vs-slider-value'))
    range.dispatchEvent(new PointerEvent('pointerleave',{pointerType:'mouse'}))
    const closed = [...document.querySelectorAll('#control-5 .vs-slider')].find(node => node.textContent.includes('Podobieństwo'))
    assert('Wariant zwinięty ma badge i ukryty panel', closed.querySelector('button').getAttribute('aria-expanded')==='false' && closed.querySelector('[id$="-panel"]').hidden && closed.textContent.includes('75%'))
    closed.querySelector('button').click(); await wait()
    assert('Rozwinięcie zachowuje wartość', !closed.querySelector('[id$="-panel"]').hidden && closed.querySelector('input').value === '75')
    closed.querySelector('button').click(); await wait()
    assert('Ponowne zwinięcie ukrywa range', closed.querySelector('[id$="-panel"]').hidden)
    const disabled = document.querySelector('#control-5 .vs-disabled input')
    disabled.dispatchEvent(new PointerEvent('pointerenter',{pointerType:'mouse'})); await wait()
    assert('Wyłączony suwak nie pokazuje dymka', !document.querySelector('.vs-slider-value'))
    assert('Dostępne warianty Input', document.querySelectorAll('.vs-input[data-size]').length >= 12)
    assert('Dostępne warianty Select i ghost', !!document.querySelector('.vs-select-trigger[data-size=xs]') && !!document.querySelector('.vs-select-trigger[data-variant=ghost]'))
    const groupTrigger = document.querySelector('[aria-label="Grupy i przewijanie"]')
    groupTrigger.click(); await wait()
    assert('Lista ma nazwane grupy', document.querySelectorAll('[role=listbox] [role=group]').length === 2)
    assert('Wyłączona opcja jest oznaczona', !!document.querySelector('[role=option][aria-disabled=true]'))
    assert('Przewijanie ma działający przycisk', !!document.querySelector('.vs-select-scroll-down'))
    document.querySelector('[role=listbox]').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true})); await wait()
    const form = document.querySelector('[data-demo-form]')
    fill(form.querySelector('input[name=project]'),'Projekt testowy'); await wait()
    form.querySelector('[role=switch]').click(); await wait()
    const formData = new FormData(form)
    assert('FormData zawiera tekst i listę', formData.get('project')==='Projekt testowy' && formData.get('language')==='pl')
    assert('Wyłączony Switch nie trafia do FormData', !formData.has('enabled'))
    form.reset(); await wait()
    assert('Reset formularza odtwarza pola i Switch', form.querySelector('input[name=project]').value==='Przykładowy projekt' && form.querySelector('[role=switch]').getAttribute('aria-checked')==='true' && new FormData(form).has('enabled'))
    const orb = document.querySelector('.theme-demo-grid .theme-orb')
    orb.closest('.vs-tooltip-trigger').dispatchEvent(new PointerEvent('pointerenter',{pointerType:'mouse'})); await wait(450)
    assert('Podpowiedź motywu jest systemowym Tooltip', visible(document.querySelector('[role=tooltip]')) && document.querySelector('[role=tooltip]').textContent.includes('trybie jasnym'))
    assert('Tooltip jest powiązany z kulką', orb.getAttribute('aria-describedby') === document.querySelector('[role=tooltip]').id)
    document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true})); await wait()
    assert('Escape ukrywa Tooltip', !document.querySelector('[role=tooltip]'))
    button('Utwórz motyw',document.querySelector('.theme-demo-header')).click(); await wait()
    assert('Edytor motywu używa natywnego modala', !!document.querySelector('dialog:modal'))
    document.querySelector('[aria-label="Zamknij edytor motywu"]').click(); await wait()
    assert('Zamknięcie usuwa modal', !document.querySelector('dialog'))
    assert('Inwentarz i wszystkie grupy są dostępne', document.querySelectorAll('section[id^=control-]').length===16 && document.querySelectorAll('.inventory>div').length>=22)
    assert('Podgląd nie zapisał preferencji ani projektów', storageKeys.every((key,index)=>localStorage.getItem(key)===original[index]))
    assert('Brak poziomego przepełnienia', document.documentElement.scrollWidth<=innerWidth)
    button('Resetuj podgląd').click(); await wait()
    return { passed:checks.length, total:checks.length, checks }
  } catch(error) { return { passed:checks.filter(check=>check.passed).length,total:checks.length,error:String(error),checks } }
}
