import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../src/lib/history-view.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { filterRecordings, groupRecordings, historyDateLabel, relativeRecordingTime } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const now = new Date(2026, 9, 19, 12).getTime(), day = 86400000;
const row = (id, age, extra = {}) => ({ id, title: id, text: 'Zażółć gęślą jaźń', voice: 'Głos Alfa', kind: 'audio', created: new Date(now - age).toISOString(), ...extra });
const rows = [row('older', 3 * day, { source: 'import', text: '' }), row('today', 60000, { modelId: 'omnivoice', modelName: 'OmniVoice', source: 'generation' }), row('yesterday', day), row('invalid', 0, { created: 'invalid' })];
const empty = { query: '', voice: '', model: '', date: '', source: '' };
assert.equal(filterRecordings(rows, { ...empty, query: 'ZAŻÓŁĆ' }, now).length, 3);
assert.deepEqual(filterRecordings(rows, { ...empty, model: 'omnivoice', source: 'generation', date: 'today' }, now).map(r => r.id), ['today']);
assert.equal(filterRecordings(rows, { ...empty, model: 'unknown' }, now).length, 3);
assert.equal(filterRecordings(rows, { ...empty, source: 'unknown' }, now).length, 2);
assert.deepEqual(groupRecordings(rows, now).map(g => g.label), ['Dzisiaj', 'Wczoraj', '16 października 2026', 'Bez daty']);
assert.equal(groupRecordings(rows, now, true)[0].rows[0].id, 'older');
assert.equal(historyDateLabel(new Date(2026, 9, 18, 23, 59).toISOString(), new Date(2026, 9, 19, 0, 1).getTime()), 'Wczoraj');
assert.equal(relativeRecordingTime(new Date(now - 26 * 60000).toISOString(), now), '26 minut temu');
assert.equal(relativeRecordingTime('invalid', now), 'Brak daty');
assert.equal(rows[0].id, 'older', 'Sorting must not mutate stored history');
console.log('History: 10 assertions passed (search, combined filters, legacy metadata, date groups, midnight, sorting and relative time).');
