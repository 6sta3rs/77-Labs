// Interaction smoke test for the 0.2 UI. Never submits a speech render.
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const checks=[];
const assert=(name,condition)=>{checks.push({name,passed:Boolean(condition)});if(!condition)throw new Error(`UI check failed: ${name}`);};
const button=text=>[...document.querySelectorAll('button')].find(node=>node.textContent.trim()===text);
const fill=(input,value)=>{input.value=value;input.dispatchEvent(new Event('input',{bubbles:true}));};
const originalKeys=['voicestudio.projects.v2','voicestudio.activeProject.v2','voicestudio.appearance.v2'];
const saved=new Map(originalKeys.map(key=>[key,localStorage.getItem(key)]));
try{
  for(let attempt=0;!document.querySelector('.speech-input')&&attempt<100;attempt++)await delay(20);
  document.querySelector('.new-narration').click();await delay(20);
  assert('Minimal editor renders without the old document frame',document.querySelector('.speech-input')&&!document.querySelector('.editor-surface'));
  assert('Windows system font is explicit',getComputedStyle(document.body).fontFamily.includes('Segoe UI'));
  const cta=button('Wygeneruj mowę');
  assert('Generate action stays above audio player',cta.getBoundingClientRect().bottom<=document.querySelector('.player').getBoundingClientRect().top);
  assert('Empty text cannot be generated',cta.disabled);
  document.querySelector('[data-speech-tag-trigger]').click();await delay(30);
  const picker=document.querySelector('.tag-popover');const rect=picker.getBoundingClientRect();
  assert('Tag picker is outside the scrolling editor',picker.parentElement===document.body);
  assert('Tag picker fits the viewport',rect.top>=0&&rect.left>=0&&rect.bottom<=innerHeight&&rect.right<=innerWidth);
  [...picker.querySelectorAll('button')].find(node=>node.textContent.trim()==='Krótka pauza').click();await delay(20);
  assert('Known pause is inserted',document.querySelector('.speech-input').value.includes('[pause 250ms]'));
  assert('Tags are visually highlighted',document.querySelector('.audio-tag')?.textContent==='[pause 250ms]');
  document.querySelector('.speech-input').dispatchEvent(new KeyboardEvent('keydown',{key:'z',ctrlKey:true,bubbles:true}));await delay(20);
  assert('Undo restores the document before the tag',document.querySelector('.speech-input').value==='');
  const original='To początek... bez zmiany słów.\n\nDrugi akapit.';
  fill(document.querySelector('.speech-input'),original);await delay(20);
  button('Automatyczne pauzy').click();await delay(20);
  const tagged=document.querySelector('.speech-input').value;
  assert('Automatic pauses preserve spoken words',tagged.replace(/\[pause\]/g,'')===original);
  button('Automatyczne pauzy').click();await delay(20);
  assert('Automatic pauses are idempotent',document.querySelector('.speech-input').value===tagged);
  button('Dodaj mówcę').click();await delay(20);
  assert('More than one speaker is supported',document.querySelectorAll('.speech-block').length===2);
  const project=JSON.parse(localStorage.getItem('voicestudio.projects.v2'))[0];
  assert('Speaker blocks persist in the local project',project.blocks.length===2&&project.blocks[0].text===tagged);
  document.querySelector('[aria-label^="Wybierz głos dla mówcy 1"]').click();await delay(20);
  assert('Voice picker opens as a dialog',document.querySelector('[role=dialog]')?.getAttribute('aria-label')==='Wybierz głos');
  const choices=document.querySelectorAll('.voice-options>button');
  const voiceText=choices[Math.min(1,choices.length-1)].querySelector('strong').textContent;
  choices[Math.min(1,choices.length-1)].click();await delay(20);
  assert('Selected voice updates the speech block',document.querySelector('.voice-pill').textContent.includes(voiceText));
  const select=document.querySelector('[aria-label="Język"]');select.click();await delay(20);
  assert('Language uses a custom listbox',Boolean(document.querySelector('[role=listbox]'))&&!document.querySelector('select#language'));
  const list=document.querySelector('[role=listbox]');list.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}));list.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));await delay(20);
  assert('Keyboard selection changes language',select.textContent.includes('English'));
  button('Wygląd').click();await delay(20);
  assert('Appearance has three mode previews',document.querySelectorAll('.mode-card').length===3);
  assert('Appearance has six theme cards',document.querySelectorAll('.theme-card').length===6);
  [...document.querySelectorAll('.mode-card')].find(node=>node.textContent.includes('Jasny')).click();
  [...document.querySelectorAll('.theme-name')].find(node=>node.textContent.includes('Ocean')).click();await delay(20);
  assert('Light Ocean applies to the whole application',document.documentElement.dataset.colormode==='light'&&document.documentElement.dataset.theme==='ocean');
  assert('Theme uses the upstream T3 Ocean canvas',getComputedStyle(document.querySelector('.app-shell')).backgroundColor==='oklch(0.974199 0.002856 241.597)');
  button('Przywróć').click();await delay(20);
  assert('Appearance reset restores the dark Labs palette',document.documentElement.dataset.colormode==='dark'&&document.documentElement.dataset.theme==='studio');
  button('Tekst na mowę').click();await delay(20);
  button('Dubbing').click();await delay(20);
  assert('Dubbing workspace renders its real staged workflow',document.querySelector('.production-workspace')?.textContent.includes('Dubbing'));
  button('Audiobooki').click();await delay(20);
  assert('Audiobook workspace renders its manuscript workflow',document.querySelector('.production-workspace')?.textContent.includes('Audiobook'));
  button('Tekst na mowę').click();await delay(20);
  const audioResponse=await fetch('/demo/interface-tone.wav');
  assert('Verified synthesis WAV is available for player testing',audioResponse.ok);
  const data=new DataTransfer();data.items.add(new File([await audioResponse.blob()],'interface-tone.wav',{type:'audio/wav'}));
  const audioInput=document.querySelector('input[type=file]');audioInput.files=data.files;audioInput.dispatchEvent(new Event('change',{bubbles:true}));
  for(let attempt=0;!document.querySelector('audio')?.duration&&attempt<150;attempt++)await delay(20);
  assert('Real synthesis WAV loads in the player',document.querySelector('audio')?.duration>3);
  assert('Imported audio card keeps the decoded duration',document.querySelector('.generation-time')?.textContent==='0:03');
  assert('Real audio enables playback and download',!document.querySelector('.play-button').disabled&&document.querySelector('a[download="interface-tone.wav"]')?.href.startsWith('blob:'));
  const seek=document.querySelector('input[aria-label="Pozycja nagrania"]');seek.value='1.1';seek.dispatchEvent(new Event('input',{bubbles:true}));await delay(20);
  assert('Player seeks inside the real recording',Math.abs(document.querySelector('audio').currentTime-1.1)<.05);
  console.log(`UI_CHECKS_PASS ${JSON.stringify(checks)}`);
}catch(error){console.error(error.stack||String(error));console.log(JSON.stringify(checks));}
finally{for(const[key,value]of saved){if(value===null)localStorage.removeItem(key);else localStorage.setItem(key,value);}}
