import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const source = await readFile(new URL('../../src/lib/tools/transcription/transcription.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { audioFileError, exportTranscription, normalizeTranscription, segmentError, transcriptText, readTranscriptionHistory, saveTranscriptionHistory, TRANSCRIPTION_HISTORY_KEY, TRANSCRIPTION_HISTORY_BYTES, microphoneError } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const fixture = [{ start: 0, end: 1.234, text: 'Cześć.' }, { start: 1.234, end: 3, text: 'Zażółć gęślą jaźń.' }];
const edited = fixture.map(row => ({ ...row }));
edited[1] = { start: 1.5, end: 3.75, text: 'Poprawiona wypowiedź.' };
assert.equal(transcriptText(edited), 'Cześć.\nPoprawiona wypowiedź.');
assert.equal(exportTranscription('stary tekst', edited, 'txt'), 'Cześć.\nPoprawiona wypowiedź.');
assert.match(exportTranscription('stary tekst', edited, 'srt'), /2\n00:00:01,500 --> 00:00:03,750\nPoprawiona wypowiedź\./);
assert.match(exportTranscription('', edited, 'vtt'), /^WEBVTT\n\n00:00:00\.000 --> 00:00:01\.234/);
assert.equal(fixture[1].text, 'Zażółć gęślą jaźń.');
for (const segment of [{ start: -1, end: 1, text: 'a' }, { start: 1, end: 1, text: 'a' }, { start: NaN, end: 2, text: 'a' }, { start: 0, end: Infinity, text: 'a' }, { start: 0, end: 1, text: ' ' }, { start: 0, end: 0.0001, text: 'too short' }, { start: 0, end: 1e308, text: 'too long' }]) {
  assert.ok(segmentError([segment]));
  assert.throws(() => exportTranscription('', [segment], 'srt'));
}
assert.throws(() => exportTranscription('tekst bez czasów', [], 'srt'), /Brak segmentów/);
assert.ok(segmentError([{ start: 2, end: 3, text: 'a' }, { start: 1, end: 2, text: 'b' }]));
const normalized = normalizeTranscription({ text: 'Cześć. Zażółć gęślą jaźń.', segments: fixture, language: 'pl' });
assert.equal(normalized.language, 'pl');
assert.equal(normalized.segments.length, 2);
const partial = normalizeTranscription({ text: 'Cały tekst, również bez czasu.', segments: [fixture[0], { start: null, end: 5, text: 'również bez czasu.' }] });
assert.equal(partial.text, 'Cały tekst, również bez czasu.');
assert.deepEqual(partial.segments, []);
assert.ok(partial.warning);
assert.throws(() => normalizeTranscription({ error: 'bad' }), /nieprawidłową/);
assert.equal(normalizeTranscription({ text: 'Sam tekst.' }).text, 'Sam tekst.');
assert.equal(audioFileError({ name: 'test.WAV', type: '', size: 10 }), '');
assert.ok(audioFileError({ name: 'test.wav', type: 'audio/wav', size: 0 }));
assert.ok(audioFileError({ name: 'test.wav', type: 'audio/wav', size: 64 * 1024 * 1024 + 1 }));
assert.ok(audioFileError({ name: 'test.html', type: 'text/html', size: 10 }));
assert.match(microphoneError(new DOMException('denied', 'NotAllowedError')), /zgody na mikrofon/);
assert.match(microphoneError(new DOMException('absent', 'NotFoundError')), /Nie znaleziono mikrofonu/);

const data = new Map();
const storage = { getItem: key => data.get(key) || null, setItem: (key, value) => data.set(key, value) };
const now = '2026-10-20T12:00:00.000Z';
const result = (id, text = 'Cześć.') => ({ id, name: `${id}.wav`, text, segments: [], language: 'pl', mode: 'accurate', created: now, updated: now });
assert.deepEqual(readTranscriptionHistory(storage).results, []);
const saved = saveTranscriptionHistory(storage, [{ ...result('edit'), text: 'stary tekst', segments: edited }]);
assert.equal(saved.results[0].text, transcriptText(edited));
assert.equal(readTranscriptionHistory(storage).results[0].segments[1].end, 3.75);
const countBound = saveTranscriptionHistory(storage, Array.from({ length: 25 }, (_, index) => result(String(index))));
assert.equal(countBound.results.length, 20);
assert.equal(countBound.removed, 5);
const bytesBound = saveTranscriptionHistory(storage, [result('first', 'ą'.repeat(190_000)), result('second', 'ą'.repeat(190_000)), result('third', 'ą'.repeat(190_000))]);
assert.equal(bytesBound.results.length, 2);
assert.ok(new TextEncoder().encode(data.get(TRANSCRIPTION_HISTORY_KEY)).length <= TRANSCRIPTION_HISTORY_BYTES);
const original = data.get(TRANSCRIPTION_HISTORY_KEY);
assert.throws(() => saveTranscriptionHistory(storage, [result('huge', 'ą'.repeat(600_000))]), /przekracza limit/);
assert.equal(data.get(TRANSCRIPTION_HISTORY_KEY), original, 'An oversized result must not erase previous history.');
assert.throws(() => saveTranscriptionHistory({ ...storage, setItem() { throw new DOMException('full', 'QuotaExceededError'); } }, [result('quota')]), /full/);
assert.equal(data.get(TRANSCRIPTION_HISTORY_KEY), original);
data.set(TRANSCRIPTION_HISTORY_KEY, '{broken');
assert.throws(() => readTranscriptionHistory(storage), /odczytać/);
assert.equal(data.get(TRANSCRIPTION_HISTORY_KEY), '{broken');
data.set(TRANSCRIPTION_HISTORY_KEY, JSON.stringify({ version: 1, results: [{ ...result('bad'), segments: [{ start: -1, end: 2, text: 'x' }] }] }));
assert.throws(() => readTranscriptionHistory(storage), /nieprawidłowy wynik/);
data.set(TRANSCRIPTION_HISTORY_KEY, JSON.stringify({ version: 1, results: [result('same'), result('same')] }));
assert.throws(() => readTranscriptionHistory(storage), /nieprawidłowy wynik/);
console.log('Transcription: PASS (edited text/timing exports, invalid timing, complete raw-text recovery, audio limits, microphone errors, durable history, retention and failure preservation).');
