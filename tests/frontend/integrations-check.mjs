import { rewriteI18nImports } from '../helpers/i18n.mjs';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../../frontend/src/platform/integrations.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { LOCAL_API_BASE, LOCAL_MCP_URL, mcpClientConfig, bindingPayload, watermarkFileError, parseWatermarkResult, watermarkTitle, watermarkSettingsPath, mcpMessages, testMcpConnection, integrationError } = await import('data:text/javascript;base64,' + Buffer.from(rewriteI18nImports(js)).toString('base64'));
assert.equal(LOCAL_API_BASE, 'http://127.0.0.1:4312/v1');
assert.equal(LOCAL_MCP_URL, 'http://127.0.0.1:4312/mcp');
const config = JSON.parse(mcpClientConfig('qa-client'));
assert.equal(config.mcpServers['seventy-seven-labs'].headers['X-OmniVoice-Client-Id'], 'qa-client');
assert.deepEqual(bindingPayload(' qa-client ', ' label ', '', ''), { client_id: 'qa-client', label: 'label', profile_id: '', default_engine: '' });
assert.throws(() => bindingPayload('bad\nheader', '', '', ''));
assert.equal(watermarkFileError({ name: 'fixture.WAV', size: 32 }), '');
assert.ok(watermarkFileError({ name: 'fixture.webm', size: 32 }));
assert.ok(watermarkFileError({ name: 'fixture.wav', size: 0 }));
assert.ok(watermarkFileError({ name: 'fixture.wav', size: 64 * 1024 * 1024 + 1 }));
const negative = parseWatermarkResult({ is_watermarked: false, confidence: 0.2, is_omnivoice: false, message_bits: '', source: 'unknown' });
assert.match(watermarkTitle(negative), /Nie wykryto/);
assert.throws(() => parseWatermarkResult({ ...negative, error: 'model unavailable' }), /Nie udało się/);
assert.throws(() => parseWatermarkResult({ ...negative, confidence: NaN }));
assert.throws(() => parseWatermarkResult({ ...negative, confidence: 2 }));
assert.match(watermarkTitle({ ...negative, is_watermarked: true, is_omnivoice: false }), /źródło niepotwierdzone/);
assert.equal(watermarkSettingsPath({ invisible_enabled: true, visible_audio_enabled: false, visible_video_enabled: true }), '/watermark/settings?invisible=true&visible_audio=false&visible_video=true');
assert.ok(!integrationError(new Error('Bearer test-token-value hf_123456789abcdef sk-123456789abcdef api_key=test-secret')).includes('123456789abcdef'));
assert.match(integrationError(new Error('token=test-secret')), /ukryto/);
assert.equal(mcpMessages('event: message\ndata: {"jsonrpc":"2.0","id":1,"result":{}}\n\n')[0].id, 1);
assert.deepEqual(mcpMessages('data: {"id":'), []);
assert.throws(() => mcpMessages('data: {bad}\n\n', true));
assert.equal(mcpMessages('{"id":2,"result":{}}', true)[0].id, 2);

const calls = [];
const transport = async (path, options) => {
  calls.push({ path, ...options });
  assert.equal(path, '/mcp');
  if (options.method === 'DELETE') return new Response(null, { status: 204 });
  const body = JSON.parse(options.body);
  if (body.method === 'initialize') {
    const encoded = new TextEncoder().encode('event: message\ndata: {"jsonrpc":"2.0","id":1,"result":{"protocolVersion":"2025-11-25","serverInfo":{"name":"Źródło MCP","version":"fixture"}}}\n\n');
    return new Response(new ReadableStream({ start(controller) { controller.enqueue(encoded.subarray(0, 80)); controller.enqueue(encoded.subarray(80)); controller.close(); } }), { headers: { 'Content-Type': 'text/event-stream', 'Mcp-Session-Id': 'fixture-session-id' } });
  }
  assert.equal(options.headers['Mcp-Session-Id'], 'fixture-session-id');
  assert.equal(options.headers['MCP-Protocol-Version'], '2025-11-25');
  if (body.method === 'notifications/initialized') return new Response(null, { status: 202 });
  assert.equal(body.method, 'tools/list');
  return new Response(JSON.stringify({ jsonrpc: '2.0', id: 2, result: { tools: [{ name: 'check_health' }, { name: 'generate_speech' }] } }), { headers: { 'Content-Type': 'application/json' } });
};
const tested = await testMcpConnection(transport);
assert.equal(tested.server, 'Źródło MCP');
assert.deepEqual(tested.tools, ['check_health', 'generate_speech']);
assert.equal(calls.length, 4);
assert.equal(calls[3].method, 'DELETE');
assert.ok(!JSON.stringify(tested).includes('fixture-session-id'), 'Session credentials must not enter diagnostics.');
assert.ok(calls.every(call => !call.body || JSON.parse(call.body).method !== 'tools/call'), 'The connection test must never invoke synthesis tools.');
await assert.rejects(() => testMcpConnection(async () => new Response('disabled', { status: 404 })), /404/);
const abort = new AbortController();
const pending = testMcpConnection(async (_path, options) => options.method === 'DELETE' ? new Response(null, { status: 204 }) : new Response(new ReadableStream({}), { headers: { 'Mcp-Session-Id': 'fixture' } }), abort.signal);
setTimeout(() => abort.abort(), 20);
await assert.rejects(pending, cause => cause.name === 'AbortError');
console.log('Integrations: PASS (local addresses, binding headers, real query flags, detector errors, redaction, MCP JSON/SSE handshake, tools list, session cleanup and abort).');
