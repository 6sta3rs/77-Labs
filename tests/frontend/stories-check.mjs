import { rewriteI18nImports } from '../helpers/i18n.mjs';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const source = await readFile(new URL('../../frontend/src/tools/stories/stories.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { newStory, newStoryScene, newStoryBlock, compileStory, readStory, storyError, storyStats, storyAudioPath, moveStoryItem, applyStoryEvent, emptyStoryRender } = await import('data:text/javascript;base64,' + Buffer.from(rewriteI18nImports(js)).toString('base64'));
const story = newStory();
const voices = new Set(['narrator', 'speaker']);
assert.ok(storyError(story, voices));
story.title = 'Historia dwóch głosów';
story.settings.defaultVoice = 'narrator';
story.settings.seed = '0';
story.settings.speed = 1.1;
story.settings.format = 'm4b';
story.scenes[0].blocks[0].text = 'Cześć. To mówi narrator.';
story.scenes[0].blocks[0].pauseMs = 250;
const dialogue = newStoryBlock('speaker'); dialogue.text = 'A to odpowiedź drugiego głosu.'; dialogue.speed = 0.85;
story.scenes[0].blocks.push(dialogue);
const scene = newStoryScene('Druga scena'); scene.blocks[0].text = 'Koniec historii.';
const pause = newStoryBlock(); pause.pauseMs = 400; scene.blocks.push(pause); story.scenes.push(scene);
const before = structuredClone(story);
const compiled = compileStory(story, voices);
assert.equal(compiled.chapters.length, 2);
assert.deepEqual(compiled.chapters[0].spans.map(span => span.voice_id), ['narrator', 'speaker']);
assert.deepEqual(compiled.chapters[0].spans.map(span => span.speed), [1.1, 0.85]);
assert.equal(compiled.chapters[0].spans[0].pause_ms_after, 250);
assert.equal(compiled.chapters[1].spans[1].text, '');
assert.equal(compiled.chapters[1].spans[1].pause_ms_after, 400);
assert.equal(compiled.seed, 0, 'A zero seed is a valid explicit value.');
assert.equal(compiled.format, 'm4b');
assert.equal(compiled.metadata.title, 'Historia dwóch głosów');
assert.equal('engine' in compiled, false, 'Longform uses the shared active engine; it has no engine request field.');
assert.equal('num_step' in compiled, false, 'Unchanged quality must use backend defaults.');
assert.deepEqual(story, before, 'Compilation must not mutate the editable project.');
assert.equal(compileStory(story, voices, [scene]).chapters.length, 1);
assert.equal(compiled.postprocess_output, false, 'A block slower than 1x keeps the pauses that carry the slowdown.');
assert.equal('postprocess_output' in compileStory(story, voices, [scene]), false, 'Normal speed keeps engine post-processing defaults.');
assert.equal(storyStats(story).voices, 2);
assert.equal(storyStats(story).pauseMs, 650);
const roundtrip = readStory(JSON.parse(JSON.stringify(story)));
assert.deepEqual(roundtrip, story);
assert.deepEqual(readStory(new Proxy(story, {})), story, 'Reactive Svelte proxies must be valid save inputs.');
assert.throws(() => readStory({ ...story, settings: { ...story.settings, speed: NaN } }), /ustawienie/);
roundtrip.scenes[0].blocks[0].text = 'Niezależna kopia';
assert.notEqual(roundtrip.scenes[0].blocks[0].text, story.scenes[0].blocks[0].text);
assert.throws(() => readStory({ ...story, kind: 'audiobooks' }), /Stories/);
assert.throws(() => readStory({ ...story, version: 2 }), /Stories/);
assert.throws(() => readStory({ ...story, scenes: [story.scenes[0], story.scenes[0]] }), /sceny/);
assert.throws(() => compileStory(story, new Set(['narrator'])), /dostępny głos/);
for (const change of [copy => copy.settings.seed = '-1', copy => copy.settings.seed = '4294967296', copy => copy.settings.speed = NaN, copy => copy.scenes[0].blocks[0].pauseMs = 10001, copy => copy.scenes[0].blocks[0].speed = 0, copy => copy.scenes[1].blocks = []]) {
  const copy = structuredClone(story); change(copy); assert.ok(storyError(copy, voices)); assert.throws(() => compileStory(copy, voices));
}
const order = [{ id: 'a' }, { id: 'b' }, { id: 'c' }];
assert.deepEqual(moveStoryItem(order, 'b', -1).map(row => row.id), ['b', 'a', 'c']);
assert.deepEqual(moveStoryItem(order, 'b', 1).map(row => row.id), ['a', 'c', 'b']);
assert.deepEqual(order.map(row => row.id), ['a', 'b', 'c']);
assert.equal(moveStoryItem(order, 'a', -1), order);
assert.equal(storyAudioPath('story_abc-123.mp3'), '/audio/story_abc-123.mp3');
for (const output of ['../secret.mp3', '/etc/file.m4b', 'https://example.org/evil.mp3', 'foo.html', 'a/b.mp3', '']) assert.throws(() => storyAudioPath(output));
let progress = applyStoryEvent(emptyStoryRender(), { type: 'started', job_id: 'job', chapters: 2 });
progress = applyStoryEvent(progress, { type: 'chapter', index: 0, title: 'Pierwsza', cached: true });
progress = applyStoryEvent(progress, { type: 'chapter', index: 0, title: 'Pierwsza', cached: true });
assert.equal(progress.completed.length, 1, 'Repeated events must not inflate completed scenes.');
progress = applyStoryEvent(progress, { type: 'chapter_error', index: 1, reason: 'Brak modelu', hint: 'Zainstaluj model.' });
assert.match(progress.message, /Brak modelu.*Zainstaluj model/);
progress = applyStoryEvent(progress, { type: 'done', output: 'story_job.m4b', failed_chapters: [1] });
assert.equal(progress.phase, 'done');
assert.match(progress.message, /niepełny/);
assert.equal(progress.failed.length, 1);
assert.equal(applyStoryEvent(emptyStoryRender(), { type: 'done', output: '../bad.mp3' }).phase, 'error');
assert.equal(applyStoryEvent(progress, { type: 'error', reason: 'Dysk pełny' }).message, 'Dysk pełny');
assert.equal(applyStoryEvent(progress, { type: 'stopped' }).phase, 'stopped');
console.log('Stories: PASS (multi-voice chapter/span compilation, pauses and speeds, zero seed, project roundtrip, validation, stable ordering, output paths and truthful partial/error SSE states).');
